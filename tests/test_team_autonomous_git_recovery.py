@pytest.mark.parametrize("outcome", ["cancelled", "rejected"])
def test_ended_merge_recovery_is_retried_by_normal_wake_without_replenishing_budget(
    tmp_path, outcome
):
    from evander_team_addon.models import TeamTaskState, utc_now
    from evander_team_addon.services.runtime_service import TeamRuntimeService
    from evander_team_addon.services.domain.dependency_composition_recovery import (
        record_dependency_composition_conflict,
    )

    repo, service, blocker_id = setup_recovery(tmp_path, cause="merge_conflict", candidate_limit=2)

    def conflict(state):
        task = state.tasks["integration"]
        project_git = state.projects["project"].git
        base_tree = service.admin._managed_git_admin.reduce_commit_frontier(
            project_git.managed_repo_id,
            directory_path="root",
            base_commit_sha=task.git_base_commit_sha,
            sources=[],
        )["base_tree_hash"]
        source = state.deliverables["accepted"]
        record_dependency_composition_conflict(
            state,
            blocker=state.blockers[blocker_id],
            conflict={
                "target_task_id": task.id,
                "project_id": "project",
                "managed_repo_id": project_git.managed_repo_id,
                "directory_path": "root",
                "base_branch": "main",
                "base_commit_sha": task.git_base_commit_sha,
                "base_tree_hash": base_tree,
                "failed_dependency_task_id": source.task_id,
                "failed_deliverable_id": source.id,
                "conflict_paths": ["contribution.txt"],
                "dependency_git_sources": [
                    {
                        "dependency_task_id": source.task_id,
                        "deliverable_id": source.id,
                        "branch": source.git_refs.agent_branch,
                        "commit_sha": source.git_refs.commit_sha,
                    }
                ],
            },
            now=utc_now(),
        )
        return state

    repo.update(conflict)
    prior_ids = []
    for attempt_number in range(2):
        state, result = apply(service, blocker_id, request_id=f"merge-{attempt_number}")
        task_id = result["task_id"]
        assert task_id not in prior_ids
        prior_ids.append(task_id)
        if outcome == "cancelled":
            service.admin.cancel_task(
                task_id=task_id,
                reason_code="retry_needed",
                reason="Retain this unsuccessful attempt",
                actor_id="operator:test",
                expected_revision=state.revision,
            )
        else:
            repo.update(
                lambda latest: setattr(latest.tasks[task_id], "state", TeamTaskState.REJECTED)
            )
        TeamRuntimeService(repo).lease_due_agents(limit=1, defer_activation=True)
        incident = repo.read().git_recovery_incidents[result["incident_id"]]
        assert incident.state == "diagnosed"
        assert incident.candidate_generations == attempt_number + 1
    assert all(repo.read().tasks[key].state.value == outcome for key in prior_ids)
    preview = service.preview(blocker_id)
    assert not preview["actions"]
    assert "budget exhausted" in preview["waiting_reason"]


def accept_successor(repo, task_id, *, callback=True, deliverable_id="reviewed-successor"):
    from evander_team_addon.models import (
        Deliverable,
        DeliverableGitRefs,
        GitWorkContext,
        GitWorkContextState,
        TeamRecordState,
        TeamTaskState,
    )
    from evander_team_addon.services.domain.deliverables import _accept_deliverable_and_maybe_task
    from evander_team_addon.models import utc_now

    def accept(state):
        task = state.tasks[task_id]
        candidate = Deliverable(
            id=deliverable_id,
            task_id=task.id,
            producer_agent_id=task.owner_agent_id,
            acceptance_policy_version=1,
            acceptance_recipient_agent_id="lead",
            summary="Reviewed implementation",
            state=TeamRecordState.PENDING,
            git_refs=DeliverableGitRefs(
                branch_context_id=f"{deliverable_id}-context",
                agent_branch="agents/session-backend/recovery",
                commit_sha="e" * 40,
                submitted_commit_sha="e" * 40,
            ),
            source_deliverable_ids=list(task.deliverable_contract.pinned_source_deliverable_ids),
        )
        state.git_work_contexts[candidate.git_refs.branch_context_id] = GitWorkContext(
            id=candidate.git_refs.branch_context_id,
            agent_id=task.owner_agent_id,
            task_id=task.id,
            base_branch=task.git_base_branch,
            base_commit=task.git_base_commit_sha,
            agent_branch=candidate.git_refs.agent_branch,
            commit_sha=candidate.git_refs.commit_sha,
            state=GitWorkContextState.SUBMITTED,
        )
        state.deliverables[candidate.id] = candidate
        task.deliverable_ids.append(candidate.id)
        task.state = TeamTaskState.WAITING_FOR_REVIEW
        if callback:
            _accept_deliverable_and_maybe_task(
                state, deliverable=candidate, task=task, now=utc_now(), result={"events": []}
            )
        return state

    return repo.update(accept)


