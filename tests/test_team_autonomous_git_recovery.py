def test_upgrade_preserves_legacy_preparation_identity_and_policy_edits_do_not_rekey_work():
    from evander_team_addon.models import AgentTask, Project, ProjectGitConfig, TeamState
    from evander_team_addon.services.domain.preparation_failures import (
        task_preparation_generation,
        task_git_work_context_generation,
    )

    state = TeamState()
    state.projects["project"] = Project(
        id="project",
        team_id="team",
        lead_agent_id="lead",
        name="Legacy project",
        git=ProjectGitConfig(managed_repo_id="mr_" + "1" * 20, base_branch="main"),
    )
    state.tasks["task"] = AgentTask(
        id="task",
        project_id="project",
        owner_agent_id="worker",
        priority=1,
        title="Legacy work",
        description="Retain this checkout",
        created_by_agent_id="lead",
    )
    # Persisted identities generated by v0.66.0 / preparation contract 4 for
    # this pre-upgrade fixture. New defaults must preserve both identities.
    assert task_preparation_generation(state, "task") == "7cfe374cda3999d94df6"
    assert task_git_work_context_generation(state, "task") == "bff9bcda32ce65ebafd4"
    state.projects["project"].git.recovery.enabled = False
    state.projects["project"].git.recovery.candidate_generation_limit = 0
    assert task_preparation_generation(state, "task") == "7cfe374cda3999d94df6"
    assert task_git_work_context_generation(state, "task") == "bff9bcda32ce65ebafd4"
    state.tasks["task"].git_constraints.excluded_ancestor_shas = ["f" * 40]
    assert task_git_work_context_generation(state, "task") != "bff9bcda32ce65ebafd4"


def setup_recovery(
    tmp_path, *, cause="workspace_missing", clean=True, renewable=False, candidate_limit=3
):
    values = _state(tmp_path, clean_source=clean)
    state, managed = values[:2]
    from evander_team_addon.repository import TeamStateRepository

    repo = TeamStateRepository(tmp_path / "team")
    repo.update(lambda _: state)
    result = {}

    def fail(state):
        state.projects["project"].git.recovery.candidate_generation_limit = candidate_limit
        if renewable:
            state.tasks["integration"].git_constraints = GitBaselineConstraints(intent="snapshot")
        blocker = record_task_preparation_failure(
            state,
            task_id="integration",
            reporter_agent_id="backend",
            error="synthetic preparation rejection",
            reason_code="dependency_git_preparation_failed",
            result={},
        )
        record_incident(state, blocker=blocker, cause=cause)
        result["blocker_id"] = blocker.id
        return state

    repo.update(fail)
    return (
        repo,
        TeamGitRecoveryService(TeamAdminService(repo, managed_git_admin=managed)),
        result["blocker_id"],
    )


def apply(service, blocker_id, *, request_id="repair", action=None):
    preview = service.preview(blocker_id)
    assert preview["actions"], preview["waiting_reason"]
    return service.apply_as_operator(
        blocker_id=blocker_id,
        preview_token=preview["preview_token"],
        action_id=action or preview["actions"][0]["id"],
        request_id=request_id,
        actor_id="test-operator",
    )


def test_exact_source_retry_is_durable_and_only_resolves_after_preparation(tmp_path):
    repo, service, blocker_id = setup_recovery(tmp_path)
    original = repo.read().tasks["integration"].git_base_commit_sha
    state, result = apply(service, blocker_id)
    incident = state.git_recovery_incidents[result["incident_id"]]
    assert incident.state == "preparing"
    assert incident.resumed_at is None
    assert preparation_epoch(state, "integration") == 1
    assert state.tasks["integration"].git_base_commit_sha == original
    assert len(repo.list_outbox_records(intent_type="team.agent.wake_requested")) == 1
    replay = service.apply_as_operator(
        blocker_id=blocker_id,
        preview_token=incident.applied_requests["repair"]["preview_token"],
        action_id="reprepare",
        request_id="repair",
        actor_id="test-operator",
    )[1]
    assert replay["idempotent_replay"]
    assert preparation_epoch(repo.read(), "integration") == 1


