def test_missing_reviewed_object_is_diagnosed_at_the_source_verifier(tmp_path):
    from types import SimpleNamespace
    from evander.review_snapshots import team_deliverable_snapshot_ref
    from evander_team_addon.provider_git_errors import DependencyGitPreparationError
    from evander_team_addon.provider_git_sources import _project_repo_task_dependency_git_sources

    repo, service, _ = setup_recovery(tmp_path)
    state = repo.read()
    source = state.deliverables["accepted"]
    source.acceptance_policy_version = 2
    source.git_refs.commit_sha = "f" * 40
    source.git_refs.submitted_commit_sha = source.git_refs.reviewed_commit_sha = None
    source.git_refs.accepted_pinned_ref = team_deliverable_snapshot_ref(source.id)
    context = SimpleNamespace(
        admin_service=SimpleNamespace(managed_git_admin=service.admin._managed_git_admin)
    )
    with pytest.raises(DependencyGitPreparationError) as failed:
        _project_repo_task_dependency_git_sources(
            context,
            state=state,
            task_id="integration",
            managed_repo_id=state.projects["project"].git.managed_repo_id,
        )
    assert failed.value.cause == "reviewed_object_unavailable"
    assert failed.value.evidence["commit_sha"] == "f" * 40
    assert source.git_refs.accepted_pinned_ref == team_deliverable_snapshot_ref(source.id)


