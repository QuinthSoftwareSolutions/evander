def setup_publication_recovery(tmp_path, *, hard_pin=False):
    from evander_team_addon.models import ReleasePackage, ReleaseScopeValidation, TeamRecordState
    from evander_team_addon.repository import TeamStateRepository

    state, managed, _, pinned, newer, branch, candidate = _state(tmp_path, clean_source=True)
    from test_managed_git_service import _run

    _run("git", "switch", "main", cwd=tmp_path / "source")
    _run("git", "branch", "-D", branch, cwd=tmp_path / "source")
    source = state.tasks["contribution"]
    source.git_constraints = GitBaselineConstraints(
        intent="required" if hard_pin else "snapshot",
        required_base_commit_sha=pinned if hard_pin else None,
    )
    source.git_base_commit_sha = pinned
    state.release_packages["release"] = ReleasePackage(
        id="release",
        project_id="project",
        deliverable_ids=["accepted"],
        feature_branches=[],
        release_branch="team/team/releases/release",
        canonical_branch="main",
        base_commit_sha=pinned,
        candidate_commit_sha=candidate,
        approved_commit_sha=candidate,
        policy_version=2,
        scope_validation=ReleaseScopeValidation(state="passed"),
        state=TeamRecordState.PENDING,
    )
    repo = TeamStateRepository(tmp_path / "team")
    repo.update(lambda _: state)
    admin = TeamAdminService(repo, managed_git_admin=managed)
    from evander_team_addon.services.git_release_service import TeamGitReleaseService

    saved, _ = TeamGitReleaseService(repo).mark_release_published(
        release_package_id="release",
        success=False,
        error="destination advanced",
        outputs={
            "reason": "destination_base_mismatch",
            "destination_branch": "main",
            "destination_commit": newer,
            "expected_destination_commit_sha": pinned,
        },
    )
    incident = next(iter(saved.git_recovery_incidents.values()))
    return repo, TeamGitRecoveryService(admin), incident, pinned, newer, candidate


@pytest.mark.parametrize("hard_pin", [False, True])
def test_destination_advance_uses_exact_release_sources_and_fresh_gates(tmp_path, hard_pin):
    repo, service, incident, _, newer, candidate = setup_publication_recovery(
        tmp_path, hard_pin=hard_pin
    )
    saved = repo.read()
    assert incident.stage == "publication"
    assert saved.release_packages["release"].approved_commit_sha == candidate
    preview = service.preview(incident.blocker_id)
    if hard_pin:
        assert preview["actions"] == []
        assert "baseline" in preview["waiting_reason"]
    else:
        assert preview["actions"][0]["id"] == "renew_release", preview
        saved, result = apply(service, incident.blocker_id)
        successor = saved.tasks[result["task_id"]]
        assert successor.git_base_branch == "main"
        assert successor.git_base_commit_sha == newer
        assert successor.deliverable_contract.pinned_source_deliverable_ids == ["accepted"]
        assert successor.deliverable_ids == []
        assert saved.git_recovery_incidents[incident.id].state == "awaiting_review"
        assert saved.release_packages["release"].approved_commit_sha == candidate
