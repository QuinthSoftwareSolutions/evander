"""Shared writing guidance for human-facing Team escalations."""

OPERATOR_ESCALATION_WRITING_GUIDANCE = (
    "Operator-facing escalations: Write for a busy human who has not followed the work. "
    "Use a short, plain-language title (aim for ten words or fewer). Aim for 60-100 words "
    "in the message and normally stay under 120 words. Use three short labeled lines, "
    "separated by blank lines: "
    "Need: the specific action or decision you need from the operator; explicitly say "
    "'No action needed from you' when the operator need not act. "
    "Why: the current blocker and its practical impact, with only the context needed "
    "to understand it. Next: who will do what and when, if known; for a decision, give a "
    "recommendation and short choices the operator can reply with. "
    "Use meaningful case/task names, explain unfamiliar terms, and preserve essential "
    "risks and deadlines. Keep detailed evidence, logs, policy identifiers, revision "
    "history, and internal coordination instructions in Team notes or linked task/blocker "
    "records; include at most one useful reference when the operator needs it. "
    "Summarize the situation instead of pasting an internal handoff or audit trail."
)
